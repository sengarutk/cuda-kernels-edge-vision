"""Renders every published number from the measured results in results/*.json.

Outputs
  docs/results.md               full result tables
  README.md                     the block between RESULTS:BEGIN / RESULTS:END markers
  paper/generated/results.tex   \\res{key} values used by paper/main.tex

    python scripts/render_report.py          # regenerate
    python scripts/render_report.py --check  # fail if any output is stale or the paper uses an unknown key
"""
import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
README = ROOT / "README.md"
RESULTS_MD = ROOT / "docs" / "results.md"
PAPER_TEX = ROOT / "paper" / "main.tex"
MACROS_TEX = ROOT / "paper" / "generated" / "results.tex"
BEGIN, END = "<!-- RESULTS:BEGIN (generated by scripts/render_report.py; do not edit) -->", "<!-- RESULTS:END -->"
PEAK_DRAM_GBS = 192.0  # RTX 4050 Laptop: 96-bit bus x 16 Gbps GDDR6

PRE_METHODS = ["eager_fp32", "compiled_fp32", "triton_fp32", "triton_2d_fp32",
               "eager_fp16", "compiled_fp16", "triton_fp16"]
PRE_LABELS = {"eager_fp32": "Eager FP32", "compiled_fp32": "Inductor FP32", "triton_fp32": "Triton 1D FP32",
              "triton_2d_fp32": "Triton 2D FP32", "eager_fp16": "Eager FP16",
              "compiled_fp16": "Inductor FP16", "triton_fp16": "Triton 1D FP16"}
FILTER_LABELS = {"eager": "Eager (1 sync)", "compiled": "Inductor (1 sync)", "triton": "Triton fused (1 sync)",
                 "triton_kernel_only": "Triton kernel only, [84, N]",
                 "triton_kernel_only_row_major": "Triton kernel only, [N, 84]"}
STAGE_LABELS = {"h2d": "H2D", "preprocess": "Preprocess", "inference": "Inference",
                "postprocess": "Postprocess", "filter": "Filter", "nms": "NMS"}


def load(name: str) -> Optional[dict]:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def f1(x: float) -> str:
    return f"{x:.1f}"


def f2(x: float) -> str:
    return f"{x:.2f}"


def table(headers: List[str], rows: List[List[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def slug(config: str) -> str:
    return config.replace(" ", "")


class Report:
    def __init__(self):
        self.pre, self.flt, self.pipe = load("preprocess"), load("filter"), load("pipelines")
        self.ncu = load("ncu_summary")
        self.values: Dict[str, str] = {}

    def put(self, key: str, value: str) -> str:
        self.values[key] = value
        return value

    # ---------------------------------------------------------------- environment
    def environment(self) -> str:
        env = next(d["environment"] for d in (self.pre, self.flt, self.pipe) if d)
        fields = [("GPU", "gpu"), ("Compute capability", "compute_capability"), ("SMs", "sm_count"),
                  ("L2 cache (MB)", "l2_cache_mb"), ("GPU memory (GB)", "gpu_memory_gb"),
                  ("Driver", "driver"), ("CUDA runtime (PyTorch)", "cuda_runtime"), ("PyTorch", "torch"),
                  ("Triton", "triton"), ("torchvision", "torchvision"), ("NumPy", "numpy"),
                  ("Ultralytics", "ultralytics"), ("Python", "python"), ("OS", "os"),
                  ("Kernel", "kernel"), ("CPU", "cpu")]
        for _, k in fields:
            self.put(f"env/{k}", str(env[k]))
        rows = [[label, str(env[k])] for label, k in fields]
        if self.ncu:
            version = self.ncu["meta"].get("ncu_version", "")
            match = re.search(r"\d{4}\.\d+\.\d+", version)
            rows.append(["Nsight Compute", self.put("env/ncu", match.group(0) if match else version)])
        runs = [[d["benchmark"], d["environment"]["timestamp_utc"], d["environment"]["git_commit"]
                 + (" (dirty)" if d["environment"]["git_dirty"] else "")]
                for d in (self.pre, self.flt, self.pipe) if d]
        return (table(["Item", "Value"], rows) + "\n\n" +
                table(["Result file", "Measured at (UTC)", "Code commit"], runs))

    # ---------------------------------------------------------------- preprocessing
    def preprocessing(self) -> str:
        res = self.pre["results"]
        resolutions = list(dict.fromkeys(r["resolution"] for r in res))
        get = {(r["resolution"], r["method"]): r for r in res}
        dev_rows, host_rows, bw_rows = [], [], []
        for rz in resolutions:
            dev_row, host_row = [rz], [rz]
            for m in PRE_METHODS:
                r = get[(rz, m)]
                base = f"pre/{m}/{rz}"
                dev_row.append(self.put(f"{base}/dev", f1(r["device_us"]["p50"])))
                host_row.append(self.put(f"{base}/host", f1(r["host_us"]["p50"])))
                self.put(f"{base}/devp95", f1(r["device_us"]["p95"]))
                self.put(f"{base}/bw", f1(r["effective_bandwidth_gbs"]))
            dev_rows.append(dev_row)
            host_rows.append(host_row)
            t, e, c, d2 = (get[(rz, m)]["device_us"]["p50"] for m in
                           ("triton_fp32", "eager_fp32", "compiled_fp32", "triton_2d_fp32"))
            th, eh = get[(rz, "triton_fp32")]["host_us"]["p50"], get[(rz, "eager_fp32")]["host_us"]["p50"]
            t16, c16 = get[(rz, "triton_fp16")]["device_us"]["p50"], get[(rz, "compiled_fp16")]["device_us"]["p50"]
            bw_rows.append([
                rz,
                self.put(f"pre/{rz}/bw_triton", f1(get[(rz, 'triton_fp32')]["effective_bandwidth_gbs"])),
                self.put(f"pre/{rz}/speedup_vs_eager", f2(e / t)),
                self.put(f"pre/{rz}/speedup_vs_compiled", f2(c / t)),
                self.put(f"pre/{rz}/fp16_speedup_vs_compiled", f2(c16 / t16)),
                self.put(f"pre/{rz}/twod_slowdown", f2(d2 / t)),
                self.put(f"pre/{rz}/host_speedup_vs_eager", f2(eh / th)),
            ])
        for metric in ("speedup_vs_eager", "speedup_vs_compiled", "twod_slowdown",
                       "fp16_speedup_vs_compiled", "host_speedup_vs_eager"):
            vals = [float(self.values[f"pre/{rz}/{metric}"]) for rz in resolutions]
            self.put(f"pre/{metric}/min", f2(min(vals)))
            self.put(f"pre/{metric}/max", f2(max(vals)))
        heads = ["Resolution"] + [PRE_LABELS[m] for m in PRE_METHODS]
        err = max(r["max_abs_err_vs_eager_fp32"] for r in res if r["method"].endswith("fp32"))
        self.put("pre/max_err_fp32", f"{err:.1e}")
        return "\n\n".join([
            "**Device time, p50 (µs)**: GPU execution only, cold L2, launch overhead hidden.",
            table(heads, dev_rows),
            "**Host latency, p50 (µs)**: call to completed synchronize, cold L2; includes Python "
            "dispatch and kernel launches.",
            table(heads, host_rows),
            "**Derived (FP32 unless noted)**: effective throughput = compulsory bytes (3 B read + "
            "12 B written per pixel) / device time. It can exceed the "
            f"{PEAK_DRAM_GBS:.0f} GB/s DRAM peak: up to 24 MB of a kernel's output may still be in "
            "L2 (not yet written back) when it finishes, which is also where the next pipeline stage "
            "reads it from.",
            table(["Resolution", "Triton throughput (GB/s)", "Device speedup vs eager",
                   "Device speedup vs Inductor", "FP16: Triton vs Inductor", "2D slowdown vs 1D",
                   "Host speedup vs eager"], bw_rows),
            f"Largest absolute deviation of any FP32 method from eager FP32: {err:.1e}.",
        ])

    # ---------------------------------------------------------------- candidate filter
    def candidate_filter(self) -> str:
        res = self.flt["results"]
        sizes = list(dict.fromkeys(r["input_size"] for r in res))
        rows = []
        for s in sizes:
            sub = [r for r in res if r["input_size"] == s]
            n, k = sub[0]["num_candidates"], sub[0]["num_survivors"]
            self.put(f"filter/{s}/cands", str(n))
            self.put(f"filter/{s}/kept", str(k))
            for r in sub:
                base = f"filter/{s}/{r['method']}/{r['l2']}"
                dev = self.put(f"{base}/dev", f1(r["device_us"]["p50"]))
                host = self.put(f"{base}/host", f1(r["host_us"]["p50"]))
                self.put(f"{base}/hostp95", f1(r["host_us"]["p95"]))
                rows.append([f"{s}x{s}", str(n), str(k), FILTER_LABELS[r["method"]], r["l2"],
                             dev + (" *" if r["device_us"]["includes_host_sync"] else ""), host,
                             f1(r["host_us"]["p95"])])
            for l2 in ("cold", "warm"):
                g = {r["method"]: r for r in sub if r["l2"] == l2}
                self.put(f"filter/{s}/{l2}/host_speedup_vs_eager",
                         f2(g["eager"]["host_us"]["p50"] / g["triton"]["host_us"]["p50"]))
                self.put(f"filter/{s}/{l2}/layout_ratio",
                         f2(g["triton_kernel_only_row_major"]["device_us"]["p50"]
                            / g["triton_kernel_only"]["device_us"]["p50"]))
        return "\n\n".join([
            "Inputs are real YOLOv8n head outputs for the letterboxed `bus.jpg` frame at 640x640 "
            "(8,400 candidates) and 1280x1280 (33,600 candidates); confidence threshold 0.25.",
            table(["Input", "Candidates", "Kept", "Method", "L2", "Device p50 (µs)",
                   "Host p50 (µs)", "Host p95 (µs)"], rows),
            "\\* Includes the device-to-host read of the survivor count, so GPU idle time while the "
            "host synchronizes is part of the measurement. Kernel-only rows launch the Triton kernel "
            "without reading the count.",
        ])

    # ---------------------------------------------------------------- pipelines
    def pipelines(self) -> str:
        parts = []
        for kind in ("anomaly", "detection"):
            entries = self.pipe["results"][kind]
            base_p50 = entries[0]["e2e_host_us"]["p50"]
            stages = list(entries[0]["stages"])
            stage_rows, e2e_rows = [], []
            for e in entries:
                cfg = slug(e["config"])
                if e["stages"]:
                    row = [e["config"]]
                    for st in stages:
                        v = e["stages"][st]
                        h = self.put(f"pipe/{kind}/{cfg}/{st}/host", f1(v["host_us"]["p50"]))
                        d = self.put(f"pipe/{kind}/{cfg}/{st}/dev", f1(v["device_us"]["p50"]))
                        row.append(f"{h} / {d}" + (" *" if v["device_us"]["includes_host_sync"] else ""))
                    stage_rows.append(row)
                x = e["e2e_host_us"]
                gain = (base_p50 - x["p50"]) / base_p50 * 100
                self.put(f"pipe/{kind}/{cfg}/e2e", f1(x["p50"]))
                self.put(f"pipe/{kind}/{cfg}/e2ems", f"{x['p50'] / 1000:.3f}")
                self.put(f"pipe/{kind}/{cfg}/p95", f1(x["p95"]))
                self.put(f"pipe/{kind}/{cfg}/spread", f1(x["block_median_spread_pct"]))
                self.put(f"pipe/{kind}/{cfg}/gain", f1(gain))
                out = e["outputs"]
                desc = (f"{out['num_candidates']} → {out['num_detections']}" if kind == "detection"
                        else f"{out['anomaly_score']:.4f}")
                e2e_rows.append([e["config"], f"{x['p50'] / 1000:.3f}", f"{x['p95'] / 1000:.3f}",
                                 f"{gain:+.1f}%", f1(x["block_median_spread_pct"]), desc])
            graphed = {("triton" in e["config"]): e["e2e_host_us"]["p50"]
                       for e in entries if "cuda-graph" in e["config"]}
            if len(graphed) == 2:
                self.put(f"pipe/{kind}/graph_triton_vs_eager",
                         f1((graphed[False] - graphed[True]) / graphed[False] * 100))
            n_samples = entries[0]["e2e_host_us"]["n"]
            out_head = "Candidates → detections" if kind == "detection" else "Anomaly score"
            parts += [
                f"### {kind.capitalize()} pipeline",
                f"**End-to-end host latency** ({n_samples} frames per configuration in "
                f"{len(entries[0]['e2e_host_us']['block_medians'])} interleaved blocks; positive "
                "reduction = faster than the first row):",
                table(["Configuration", "p50 (ms)", "p95 (ms)", "Latency reduction vs first row",
                       "Block spread (%)", out_head], e2e_rows),
                "**Per-stage time, p50 (µs), host latency / device time**:",
                table(["Configuration"] + [STAGE_LABELS[s] for s in stages], stage_rows),
            ]
        parts.append("\\* Stage contains a device-to-host synchronization (top-k score read-back or "
                     "survivor count), so its device time includes GPU idle time. CUDA-graph "
                     "configurations replay their stages as one graph and are measured end to end only.")
        return "\n\n".join(parts)

    # ---------------------------------------------------------------- Nsight Compute
    def nsight(self) -> str:
        rows = []
        for name, t in self.ncu["targets"].items():
            self.put(f"ncu/{name}/total", f1(t["total_duration_us"]))
            self.put(f"ncu/{name}/kernels", str(t["num_kernels"]))
            main = max(range(len(t["kernels"])), key=lambda i: t["kernels"][i]["duration_us"])
            for i, k in enumerate(t["kernels"]):
                bases = [f"ncu/{name}/{i}"] + ([f"ncu/{name}/main"] if i == main else [])
                vals = {
                    "dur": f1(k["duration_us"]), "regs": f"{k['registers_per_thread']:.0f}",
                    "theo": f1(k["theoretical_occupancy_pct"]), "occ": f1(k["achieved_occupancy_pct"]),
                    "dram": f1(k["dram_throughput_pct_peak"]), "gbs": f1(k["achieved_dram_gbs"]),
                    "ldeff": f1(k["global_load_sector_efficiency_pct"]),
                    "steff": f1(k["global_store_sector_efficiency_pct"]),
                    "l1": f1(k["l1_hit_rate_pct"]), "l2": f1(k["l2_hit_rate_pct"]),
                    "stall": (k["dominant_stall"] or "-").replace("_", " "),
                    "stallpct": f1(k["stall_share_pct"].get(k["dominant_stall"], 0.0)) if k["dominant_stall"] else "-",
                }
                vals["wrmb"] = f1(k["dram_write_bytes"] / 1e6)
                vals["rdmb"] = f1(k["dram_read_bytes"] / 1e6)
                for base in bases:
                    for key, v in vals.items():
                        self.put(f"{base}/{key}", v)
                rows.append([name if i == 0 else "", str(k["kernel"])[:48], vals["dur"], vals["regs"],
                             vals["theo"], vals["occ"], vals["gbs"], vals["dram"], vals["ldeff"],
                             vals["steff"], f"{vals['stall']} ({vals['stallpct']}%)"])
        meta = self.ncu["meta"]
        return "\n\n".join([
            f"Collected with {meta.get('ncu_version', 'Nsight Compute')}; clock control: "
            f"{meta.get('clock_control', '?')}; cache control: {meta.get('cache_control', '?')}. "
            "Durations are therefore at base clocks with cold caches and are not directly comparable "
            "with the benchmark tables above.",
            table(["Target", "Kernel", "Duration (µs)", "Regs/thread", "Theor. occ. (%)",
                   "Achieved occ. (%)", "DRAM (GB/s)", "DRAM (% peak)", "Load sector eff. (%)",
                   "Store sector eff. (%)", "Dominant stall (share)"], rows),
            "Stall shares are each reason's fraction of all stalled-warp samples per issued instruction "
            "(`smsp__average_warps_issue_stalled_*_per_issue_active`), excluding `selected`.",
        ])

    # ---------------------------------------------------------------- outputs
    def results_md(self) -> str:
        sections = ["# Measured Results",
                    "Generated by `scripts/render_report.py` from `results/*.json`; do not edit by hand. "
                    "Methodology: [methodology.md](methodology.md).",
                    "## Environment", self.environment()]
        if self.pre:
            sections += ["## Isolated preprocessing (uint8 HWC → normalized CHW)", self.preprocessing()]
        if self.flt:
            sections += ["## Isolated YOLO candidate filter", self.candidate_filter()]
        if self.pipe:
            sections += ["## Pipelines", self.pipelines()]
        if self.ncu:
            sections += ["## Nsight Compute", self.nsight()]
        return "\n\n".join(sections) + "\n"

    def readme_block(self) -> str:
        v = self.values
        rz = ["256x256", "640x640", "1280x720", "1920x1080", "3840x2160"]
        pre_rows = [[r, v[f"pre/eager_fp32/{r}/dev"], v[f"pre/compiled_fp32/{r}/dev"], v[f"pre/triton_fp32/{r}/dev"],
                     v[f"pre/triton_2d_fp32/{r}/dev"], v[f"pre/{r}/bw_triton"], v[f"pre/{r}/speedup_vs_eager"] + "x",
                     v[f"pre/{r}/speedup_vs_compiled"] + "x"] for r in rz if f"pre/{r}/bw_triton" in v]
        lines = [BEGIN, "",
                 f"Measured on {v['env/gpu']} ({v['env/compute_capability']}, {v['env/l2_cache_mb']} MB L2), "
                 f"PyTorch {v['env/torch']}, Triton {v['env/triton']}, {v['env/os']}. Full tables: "
                 "[docs/results.md](docs/results.md).", "",
                 "**Isolated preprocessing, FP32, device time p50 (µs), cold L2**", "",
                 table(["Resolution", "Eager", "Inductor", "Triton 1D", "Triton 2D", "Triton throughput (GB/s)",
                        "vs Eager", "vs Inductor"], pre_rows), ""]
        flt_rows = []
        for s in ("640", "1280"):
            if f"filter/{s}/cands" in v:
                flt_rows.append([f"{s}x{s} ({v[f'filter/{s}/cands']} cands, {v[f'filter/{s}/kept']} kept)",
                                 v[f"filter/{s}/eager/warm/host"], v[f"filter/{s}/compiled/warm/host"],
                                 v[f"filter/{s}/triton/warm/host"],
                                 v[f"filter/{s}/triton_kernel_only/warm/dev"]])
        lines += ["**YOLOv8n candidate filter, host latency p50 (µs), warm L2**", "",
                  table(["Input", "Eager", "Inductor", "Triton fused", "Triton kernel alone (device)"],
                        flt_rows), ""]
        for kind in ("anomaly", "detection"):
            rows = [[e["config"], v[f"pipe/{kind}/{slug(e['config'])}/e2ems"],
                     v[f"pipe/{kind}/{slug(e['config'])}/gain"] + "%"]
                    for e in self.pipe["results"][kind]]
            title = ("Anomaly pipeline (256x256 autoencoder)" if kind == "anomaly"
                     else "Detection pipeline (640x640 YOLOv8n + NMS)")
            lines += [f"**{title}, end-to-end host latency p50 (ms)**", "",
                      table(["Configuration", "p50 (ms)", "Latency reduction vs first row"], rows), ""]
        lines.append(END)
        return "\n".join(lines)

    def macros_tex(self) -> str:
        out = ["% Generated by scripts/render_report.py from results/*.json; do not edit.",
               "\\makeatletter",
               "\\newcommand{\\res}[1]{\\@ifundefined{res@#1}{\\textbf{??#1??}}{\\@nameuse{res@#1}}}"]
        for k, val in sorted(self.values.items()):
            safe = (val.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("%", "\\%")
                    .replace("&", "\\&").replace("#", "\\#").replace("@", "\\@").replace("(R)", "")
                    .replace("→", "$\\rightarrow$"))
            out.append(f"\\@namedef{{res@{k}}}{{{safe}}}")
        out.append("\\makeatother")
        return "\n".join(out) + "\n"


def splice_readme(text: str, block: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit("README.md is missing the RESULTS markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    report = Report()
    if not (report.pre and report.flt and report.pipe):
        print("results/preprocess.json, filter.json and pipelines.json are required", file=sys.stderr)
        return 1
    outputs = {RESULTS_MD: report.results_md()}
    outputs[README] = splice_readme(README.read_text(), report.readme_block())
    outputs[MACROS_TEX] = report.macros_tex()

    used = set(re.findall(r"\\res\{([^}]*)\}", PAPER_TEX.read_text())) if PAPER_TEX.exists() else set()
    unknown = sorted(used - set(report.values))
    if unknown:
        print("paper/main.tex uses unknown result keys:\n  " + "\n  ".join(unknown), file=sys.stderr)
        return 1

    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"[rendered] {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run python scripts/render_report.py): " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    if args.check:
        print(f"Report is up to date ({len(report.values)} values, {len(used)} used by the paper).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
